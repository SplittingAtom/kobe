#!/usr/bin/env node
// KOBE-616: compiles the Kobe guide (docs/guide/**/*.md at the repository root) into
// lib/docs/guide.generated.ts, so the web bundle carries it and nothing is read from outside the
// app at runtime. Runs before `next build`, `next dev`, typecheck and the tests (package.json);
// the output is gitignored. Fails with every problem listed (lib/docs/guide-loader.ts).
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";
import { buildGuide, GuideBuildError } from "../lib/docs/guide-loader.ts";

const WEB = fileURLToPath(new URL("..", import.meta.url));
// Arguments (tests only): another guide directory and output file.
const GUIDE = process.argv[2] ?? join(WEB, "..", "..", "docs", "guide");
const OUT = process.argv[3] ?? join(WEB, "lib", "docs", "guide.generated.ts");

function walk(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) return walk(path);
    return entry.isFile() && entry.name.endsWith(".md") ? [path] : [];
  });
}

let files;
try {
  files = walk(GUIDE)
    .sort()
    .map((path) => ({
      path: relative(GUIDE, path).split(sep).join("/"),
      content: readFileSync(path, "utf8"),
    }));
} catch (e) {
  console.error(`generate-guide: cannot read ${GUIDE}: ${e.message}`);
  process.exit(1);
}

let pages;
try {
  pages = buildGuide(files);
} catch (e) {
  if (e instanceof GuideBuildError) {
    console.error(`generate-guide: ${e.message}`);
    process.exit(1);
  }
  throw e;
}

const source = `// Generated by apps/web/scripts/generate-guide.mjs from docs/guide (KOBE-616). Do not edit.
import type { GuidePage } from "./guide-loader";

export const GUIDE_PAGES: readonly GuidePage[] = ${JSON.stringify(pages, null, 2)};
`;
mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, source);
console.log(`generate-guide: ${pages.length} page(s) -> ${relative(WEB, OUT)}`);
