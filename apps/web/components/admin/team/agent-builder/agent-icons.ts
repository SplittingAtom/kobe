/** Icon names matching `query` (each word, anywhere in the name; spaces read as hyphens). */
export function searchAgentIcons(query: string): string[] {
  const words = query
    .trim()
    .toLowerCase()
    .split(/[\s-]+/)
    .filter(Boolean);
  return [...AGENT_ICONS.keys()].filter((name) => words.every((w) => name.includes(w)));
}
