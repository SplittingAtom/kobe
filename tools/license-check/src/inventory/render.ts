/** Renders THIRD_PARTY_LICENSES.md and NOTICE from the inventory rows. */
import type { LicenseExceptions } from "../policy.js";
import type { Notice, Row } from "./rows.js";
import type { HandRow, HandSection } from "./source.js";

export interface GeneratedTable {
  readonly title: string;
  readonly intro: string;
  readonly rows: readonly Row[];
  readonly exceptionsPath?: string;
  readonly exceptions?: LicenseExceptions;
}

export interface Document {
  readonly generated: readonly GeneratedTable[];
  readonly sections: readonly HandSection[];
  /** Generated tables appended to a hand section (by section id). */
  readonly appended: Readonly<Record<string, readonly GeneratedTable[]>>;
  /** License decisions queued for the next gate review. */
  readonly pending: readonly string[];
}

function cell(text: string): string {
  return text
    .replace(/\s*\n\s*/g, " ")
    .replace(/\|/g, "\\|")
    .trim();
}

function line(cells: readonly string[]): string {
  return `| ${cells.map(cell).join(" | ")} |`;
}

const HEADER = ["Component", "Version", "License (SPDX)", "How used", "Where", "License text"];

function rowTable(rows: readonly Row[]): string {
  return [
    line(HEADER),
    line(HEADER.map(() => "---")),
    ...rows.map((r) =>
      line([
        r.component,
        r.version,
        r.excepted ? `${r.license} (exception)` : r.license,
        r.use,
        r.where,
        `[license](${r.link})`,
      ]),
    ),
  ].join("\n");
}

function notes(row: HandRow): string {
  const approval = row.approval
    ? `Approved by ${row.approval.by} on ${row.approval.on}${row.approval.ref ? ` (${row.approval.ref})` : ""}.`
    : row.pending
      ? "Pending gate review."
      : "";
  return [row.reason ?? "", approval].filter((s) => s !== "").join(" ");
}

function handTable(rows: readonly HandRow[]): string {
  const header = [...HEADER, "Notes"];
  return [
    line(header),
    line(header.map(() => "---")),
    ...rows.map((r) =>
      line([r.component, r.version, r.license, r.use, r.where, `[license](${r.link})`, notes(r)]),
    ),
  ].join("\n");
}

function exceptionList(path: string, exceptions: LicenseExceptions): string {
  const items = Object.entries(exceptions)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(
      ([name, e]) =>
        `- \`${name}\` ${e.versions.join(", ")} (${e.license}): ${cell(e.reason)} ` +
        (e.approvedBy && e.approvedOn
          ? `Approved by ${e.approvedBy} on ${e.approvedOn}.`
          : "Pending gate review."),
    );
  return [`Documented exceptions (\`${path}\`):`, "", ...items].join("\n");
}

function summary(rows: readonly Row[]): string {
  const shipped = rows.filter((r) => !r.use.startsWith("dev-only") && r.use !== "test-only");
  return `${rows.length} packages, ${shipped.length} of them shipped in an image.`;
}

function generatedBlock(table: GeneratedTable, level: string): string[] {
  const parts = [`${level} ${table.title}`, "", table.intro, "", summary(table.rows), ""];
  parts.push(rowTable(table.rows), "");
  if (table.exceptions && table.exceptionsPath && Object.keys(table.exceptions).length > 0) {
    parts.push(exceptionList(table.exceptionsPath, table.exceptions), "");
  }
  return parts;
}

export function renderInventory(doc: Document): string {
  const parts = [
    "# Third-party licenses",
    "",
    "<!-- Generated by `pnpm licenses:update` (tools/license-check) from tools/license-check/inventory.yaml,",
    "     pnpm-lock.yaml, the image license reports and the exception files. Do not edit by hand:",
    "     `pnpm license:check` fails when this file is stale. -->",
    "",
    "Kobe is licensed under the Apache License 2.0 ([LICENSE](LICENSE)); attribution notices of",
    "bundled components are in [NOTICE](NOTICE). This file lists every third-party component Kobe",
    "uses, ships, or depends on at runtime. The policy (MIT/Apache/BSD/MPL family; anything else",
    "needs a version-pinned exception that Chris signs off) is in",
    "[docs/licensing.md](docs/licensing.md).",
    "",
    "How used: **linked** (imported by Kobe code), **bundled** (shipped inside a Kobe image),",
    "**separate process** (a program Kobe runs or talks to, not linked), **optional** (off by",
    "default), **external** (operated by the site, not shipped by Kobe), **dev-only** /",
    "**test-only** (never shipped).",
    "",
  ];
  parts.push("## Pending gate review", "");
  parts.push(
    doc.pending.length === 0
      ? "Nothing is pending: every component outside the allowed family has Chris's approval."
      : [
          "Outside the allowed family and not decided yet; every gate review clears this list with",
          "Chris (`pnpm license:gate` fails while it is not empty):",
          "",
          ...doc.pending.map((p) => `- ${cell(p)}`),
        ].join("\n"),
    "",
  );
  for (const table of doc.generated) parts.push(...generatedBlock(table, "##"));
  for (const section of doc.sections) {
    parts.push(`## ${section.title}`, "", section.intro, "", handTable(section.rows), "");
    for (const table of doc.appended[section.id] ?? []) parts.push(...generatedBlock(table, "###"));
  }
  return `${parts.join("\n").trimEnd()}\n`;
}

const RULE = "-".repeat(80);

export function renderNotice(header: string, notices: readonly Notice[]): string {
  const parts = [
    header.trimEnd(),
    "",
    "This product bundles third-party components; their licenses are listed in",
    "THIRD_PARTY_LICENSES.md. The NOTICE files those components ship follow (Apache License 2.0,",
    "section 4(d)). Generated by `pnpm licenses:update`; do not edit by hand.",
  ];
  for (const n of notices) {
    parts.push("", RULE, `${n.component} ${n.version} (${n.where})`, RULE, "", n.text.trimEnd());
  }
  return `${parts.join("\n")}\n`;
}
